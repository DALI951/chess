/**
 * GENERATE THE CROSS-LANGUAGE MOVE FIXTURE.
 *
 * The browser engine (assets/js/engine.js) and the server engine
 * (api/includes/Engine.php) are two implementations of the same rules. The only
 * way to know they still agree is to make them agree against a fixture neither
 * of them produced: this script writes the move list + perft counts that PHP
 * must reproduce exactly.
 *
 *   node tools/gen-move-fixtures.mjs        # writes tests/fixtures/moves.json
 *   node tools/gen-move-fixtures.mjs --check   # fails if the file is stale
 *
 * Regenerate ONLY when a rules change is intentional: a diff here means the
 * browser and the server would disagree about the game.
 *
 * @author DALI951
 */
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { Chess } from '../assets/js/engine.js';
import { POSITIONS, moveKeys } from '../tests/js/positions.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, '..', 'tests', 'fixtures', 'moves.json');

const DEPTHS = [1, 2, 3];

const fixture = {
  note: 'Generated by tools/gen-move-fixtures.mjs — do not hand-edit. tests/php/ParityTest.php must reproduce every value exactly.',
  generated: new Date().toISOString().slice(0, 10),
  positions: POSITIONS.map((fen) => {
    const chess = new Chess(fen);
    const perft = {};
    for (const d of DEPTHS) perft[d] = chess.perftFast(d);
    return {
      fen,
      moves: moveKeys(chess),
      san: chess.moves().map((m) => m.san).sort(),
      fenRoundTrip: chess.fen(),
      inCheck: chess.inCheck(),
      isCheckmate: chess.isCheckmate(),
      isStalemate: chess.isStalemate(),
      endReason: chess.endReason(),
      perft,
    };
  }),
};

const json = JSON.stringify(fixture, null, 2) + '\n';

if (process.argv.includes('--check')) {
  if (!existsSync(OUT)) {
    console.error(`MISSING: ${OUT} — run: node tools/gen-move-fixtures.mjs`);
    process.exit(1);
  }
  const current = readFileSync(OUT, 'utf8');
  // ignore the date line so a regeneration on another day is not a "diff"
  const strip = (s) => s.replace(/"generated": ".*?"/, '"generated": "?"');
  if (strip(current) !== strip(json)) {
    console.error('STALE: tests/fixtures/moves.json does not match the JS engine.');
    console.error('If the rules changed on purpose: node tools/gen-move-fixtures.mjs');
    process.exit(1);
  }
  console.log(`fixture OK (${fixture.positions.length} positions)`);
} else {
  writeFileSync(OUT, json, 'utf8');
  console.log(`wrote ${OUT}`);
  console.log(`${fixture.positions.length} positions, ${fixture.positions.reduce((a, p) => a + p.moves.length, 0)} moves total`);
}
